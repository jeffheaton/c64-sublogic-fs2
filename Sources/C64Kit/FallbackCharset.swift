    /// The 37 graphics of screen codes $5B-$7F (set 2), as functions of (row, column).
    private static func graphic(_ code: UInt8, _ r: Int, _ c: Int) -> Bool {
        let midRow = r == 4, midColumn = c == 3 || c == 4
        let left = c <= 3, right = c >= 4, top = r <= 3, bottom = r >= 4
        switch code {
        case 0x5B: return midRow || midColumn                              // cross
        case 0x5C: return left && (r + c) % 2 == 0                         // left half, checkered
        case 0x5D: return midColumn                                        // vertical line
        case 0x5E: return (r + c) % 2 == 0                                 // checkered
        case 0x5F: return (r + c) % 4 == 0                                 // diagonal stripes
        case 0x60: return false
        case 0x61: return left                                             // left half block
        case 0x62: return bottom                                           // lower half block
        case 0x63: return r == 0                                           // top line
        case 0x64: return r == 7                                           // bottom line
        case 0x65: return c == 0                                           // left line
        case 0x66: return (r / 2 + c / 2) % 2 == 0                         // coarse checker
        case 0x67: return c == 7                                           // right line
        case 0x68: return bottom && (r / 2 + c / 2) % 2 == 0               // lower coarse checker
        case 0x69: return r + c <= 7                                       // upper-left triangle
        case 0x6A: return c >= 6                                           // right quarter
        case 0x6B: return midColumn || (midRow && right)                   // tee to the right
        case 0x6C: return bottom && right                                  // lower right quadrant
        case 0x6D: return (midColumn && r <= 4) || (midRow && right)       // corner up-right
        case 0x6E: return (midColumn && r >= 4) || (midRow && left)        // corner down-left
        case 0x6F: return r >= 6                                           // lower quarter
        case 0x70: return (midColumn && r >= 4) || (midRow && right)       // corner down-right
        case 0x71: return midRow || (midColumn && top)                     // tee up
        case 0x72: return midRow || (midColumn && bottom)                  // tee down
        case 0x73: return midColumn || (midRow && left)                    // tee to the left
        case 0x74: return c <= 1                                           // left quarter
        case 0x75: return c <= 2                                           // left three eighths
        case 0x76: return c >= 5                                           // right three eighths
        case 0x77: return r <= 1                                           // upper quarter
        case 0x78: return r <= 2                                           // upper three eighths
        case 0x79: return r >= 5                                           // lower three eighths
        case 0x7A: return (c == 6 && r == 2) || (c == 5 && r == 3) || (c == 4 && r == 4)
            || (c == 3 && r == 5) || (c == 2 && r == 4) || (c == 1 && r == 3)   // check mark
        case 0x7B: return bottom && left                                   // lower left quadrant
        case 0x7C: return top && right                                     // upper right quadrant
        case 0x7D: return (midColumn && r <= 4) || (midRow && left)        // corner up-left
        case 0x7E: return top && left                                      // upper left quadrant
        case 0x7F: return (top && left) || (bottom && right)               // diagonal quadrants
        default: return false
        }
    }

    private static func bits(_ rows: [String]) -> [UInt8] {
        precondition(rows.count == 8)
        return rows.map { row in
            precondition(row.count == 8)
            return row.reduce(0) { $0 << 1 | ($1 == "#" ? 1 : 0) }
        }
    }

    private static func build() -> [UInt8] {
        var rom = [UInt8](repeating: 0, count: 4096)
        func put(_ set: Int, _ code: Int, _ glyph: [UInt8]) {
            let base = (set == 2 ? 0x800 : 0) + code * 8
            for r in 0..<8 {
                rom[base + r] = glyph[r]
                rom[base + 0x400 + r] = ~glyph[r]        // reverse video, codes $80-$FF
            }
        }
        let blank = ["........"]
        for (code, rows) in shared {
            put(1, Int(code), bits(rows))
            put(2, Int(code), bits(rows))
        }
        for (k, rows) in capitals.enumerated() {
            let glyph = bits(blank + rows + blank)
            put(1, 0x01 + k, glyph)                      // set 1: A-Z at $01
            put(2, 0x41 + k, glyph)                      // set 2: A-Z at $41
        }
        for (k, rows) in lowercase.enumerated() {
            put(2, 0x01 + k, bits(blank + rows))         // set 2: a-z at $01
        }
        for code in 0x5B...0x7F {
            var glyph = [UInt8](repeating: 0, count: 8)
            for r in 0..<8 {
                for c in 0..<8 where graphic(UInt8(code), r, c) { glyph[r] |= 0x80 >> UInt8(c) }
            }
            put(2, code, glyph)
            put(1, code, glyph)
            // Set 1 shows graphics at $41-$5A too (letters live at $01-$1A there).
            if code >= 0x61 && code <= 0x7A { put(1, code - 0x20, glyph) }
        }
        return rom
    }
