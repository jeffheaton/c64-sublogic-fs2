/// An original 8 x 8 character set in the C64's style, used for text screens when no character
/// generator ROM was imported (the ROM is not on the game disk; `GameData.charROM` is optional).
///
/// It is laid out like the 4 KB ROM so the VIC presenter can use it in the ROM's place:
///
/// | Offset | Set | Screen codes |
/// |---|---|---|
/// | $000-$3FF | 1 (uppercase/graphics, `$D018` = $14) | $00 '@', $01-$1A A-Z, $1B-$3F punctuation and digits, $40 line, $41-$7F graphics |
/// | $400-$7FF | 1, reversed | $80-$FF = $00-$7F inverted |
/// | $800-$BFF | 2 (lowercase/uppercase, `$D018` = $16) | $00 '@', $01-$1A a-z, $1B-$3F as set 1, $40 line, $41-$5A A-Z, $5B-$7F graphics |
/// | $C00-$FFF | 2, reversed | |
///
/// The glyphs are drawn for this port (not taken from any ROM): capitals and digits stand on
/// rows 1-6 with blank rows 0 and 7 (lowercase x-height rows 3-6, ascenders from row 1, one
/// descender row), two-pixel stems, one-pixel bars. The line character $40 fills row 4 across
/// the whole cell, so a run of them draws a continuous rule and leads into '>' (the editor's
/// cursor arrow). Set 1 is not used by Flight Simulator II; its graphics are the same simple
/// blocks and lines as set 2's.
public enum FallbackCharset {
    /// The 4096-byte character generator image.
    public static let rom: [UInt8] = build()

    /// The 8 bytes of screen code `code` (bit 7 = reverse video) in set `set` (1 or 2).
    public static func glyph(_ code: UInt8, set: Int) -> ArraySlice<UInt8> {
        let base = (set == 2 ? 0x800 : 0) + Int(code) * 8
        return rom[base..<base + 8]
    }

